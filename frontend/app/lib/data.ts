export function initials(name: string | null | undefined) {
  if (!name?.trim()) return "??";
  return name
    .trim()
    .split(/\s+/)
    .map((part) => part[0] ?? "")
    .join("")
    .slice(0, 2)
    .toUpperCase() || "??";
}

