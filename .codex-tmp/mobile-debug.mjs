import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { join } from 'node:path';
const require=createRequire(join(homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json'));
const {chromium}=require('playwright');
const b=await chromium.launch({headless:true,channel:'chrome'});
const c=await b.newContext({viewport:{width:390,height:844},timezoneId:'Asia/Jakarta'});
const p=await c.newPage();p.on('pageerror',e=>console.log('ERROR',e.message));p.on('console',e=>{if(e.type()==='error')console.log('CONSOLE',e.text().slice(0,800));});
await p.addInitScript(()=>sessionStorage.setItem('ctd_splash_seen','1'));
await p.goto('http://localhost:3000/dashboard');await p.waitForTimeout(7000);
console.log(await p.evaluate(()=>({text:document.body.innerText.slice(0,2200),panels:document.querySelectorAll('article').length,height:document.documentElement.scrollHeight,opacity:document.querySelector('.page-view-enter')?.outerHTML.slice(0,400)})));
await p.screenshot({path:'output/mobile-redesign/debug.png',fullPage:true,scale:'css'});await b.close();
