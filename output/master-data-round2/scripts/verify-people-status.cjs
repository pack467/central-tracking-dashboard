const { launch, open, BASE } = require("./pw.cjs");
const ok = (c, l, e = "") => { console.log(`${c ? "PASS" : "FAIL"}  ${l}${e ? "  " + e : ""}`); if (!c) process.exitCode = 1; };
(async () => {
  const b = await launch(); const p = await open(b, { width: 1440, height: 900 }); p.setDefaultTimeout(8000);
  await p.goto(`${BASE}/master-data?group=team&tab=people&mock=instant`, { waitUntil: "networkidle" });
  await p.waitForSelector("[data-master-id]:visible"); await p.waitForTimeout(400);
  await p.locator("#master-filter-status").click();
  const opts = (await p.getByRole("option").allInnerTexts()).map(t => t.trim());
  ok(JSON.stringify(opts) === JSON.stringify(["Semua", "Aktif", "Nonaktif"]), "status filter: Semua, Aktif, Nonaktif", opts.join(", "));
  await p.keyboard.press("Escape");
  const row = p.locator("tbody tr").nth(3);
  await row.getByRole("button", { name: /^Aksi/ }).click();
  const items = (await p.getByRole("menuitem").allInnerTexts()).map(t => t.split("\n")[0].trim());
  ok(!items.some(t => /Arsip/.test(t)) && items.includes("Nonaktifkan"), "row menu has Nonaktifkan, no Arsipkan", items.join(", "));
  await p.keyboard.press("Escape");
  await p.locator("tbody tr").nth(3).click({ position: { x: 60, y: 20 } });
  await p.waitForSelector("section[role=dialog]"); await p.waitForTimeout(500);
  await p.getByRole("button", { name: "Aksi detail" }).click();
  const d = (await p.getByRole("menuitem").allInnerTexts()).map(t => t.split("\n")[0].trim());
  ok(!d.some(t => /Arsip/.test(t)), "detail menu has no Arsipkan", d.join(", "));
  await p.keyboard.press("Escape"); await p.keyboard.press("Escape"); await p.waitForTimeout(300);
  await p.getByRole("button", { name: /^Ubah /i }).first().click(); await p.waitForSelector("form");
  const radios = (await p.locator("form [role=radiogroup][aria-label=Status] [role=radio]").allInnerTexts()).map(t => t.trim());
  ok(JSON.stringify(radios) === JSON.stringify(["Aktif", "Nonaktif"]), "form status: Aktif, Nonaktif only", radios.join(", "));
  ok(!p.errors.filter(e => !/preload/.test(e)).length, "no console errors");
  await b.close();
})().catch(e => { console.log("FAIL", e.message.replace(/\s+/g, " ").slice(0, 250)); process.exitCode = 1; });
