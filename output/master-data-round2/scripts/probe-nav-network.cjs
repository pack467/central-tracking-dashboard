const fs = require("fs");
const { launch, open } = require("./pw.cjs");
const BASE = process.env.CTD_BASE || "http://localhost:3000";
const B = "E:/Website/Central Tracking Dashboard/Central_Tracking_Dashboard/backend/";
const env = Object.fromEntries(fs.readFileSync(B + ".env", "utf8").split(/\r?\n/).filter(l => /^[A-Z_]+=/.test(l)).map(l => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]));
const users = (l => l.users || l)(JSON.parse(fs.readFileSync(B + "prisma/seed-data/users.json", "utf8")));
const account = users.find(u => u.role_id === "1" && u.email);
(async () => {
  const browser = await launch();
  const page = await open(browser, { width: 1440, height: 900, noAuth: true });
  page.setDefaultTimeout(90000);
  await page.goto(`${BASE}/login`, { waitUntil: "networkidle" }); await page.waitForTimeout(1000);
  await page.getByLabel("Email atau ID Karyawan").fill(account.email);
  await page.getByLabel("Kata sandi", { exact: true }).fill(env.SEED_DEFAULT_PASSWORD);
  await page.getByRole("button", { name: "Masuk" }).click();
  await page.waitForURL(u => u.pathname === "/dashboard", { timeout: 90000 });
  await page.getByText("Menampilkan").first().waitFor({ state: "attached" }); await page.waitForTimeout(4000);
  const log = [];
  page.on("request", r => { if (!/\.(js|css|png|svg|woff2?|ico|map)(\?|$)/.test(r.url()) && !r.url().includes("/@") && !r.url().includes("/node_modules/") && !r.url().includes("/app/") ) log.push(`REQ  ${r.method()} ${r.resourceType()} ${r.url().replace(BASE, "").slice(0, 110)} accept=${(r.headers()["accept"] || "").slice(0, 40)}`); });
  page.on("response", r => { if (r.request().resourceType() === "fetch" || r.request().resourceType() === "document") log.push(`RES  ${r.status()} ${r.request().resourceType()} ${r.url().replace(BASE, "").slice(0, 100)} type=${(r.headers()["content-type"] || "").slice(0, 40)}`); });
  page.on("console", m => { if (/navigat|rsc|reload|hard|fallback|error/i.test(m.text())) log.push(`CON  ${m.type()} ${m.text().slice(0, 160)}`); });
  page.on("pageerror", e => log.push(`ERR  ${e.message.slice(0, 160)}`));
  await page.getByRole("link", { name: "Tickets", exact: true }).first().click();
  await page.waitForTimeout(4000);
  console.log(log.join("\n"));
  console.log("final url:", page.url().replace(BASE, ""));
  await browser.close();
})().catch(e => { console.log("FAIL", e.message.slice(0, 300)); process.exitCode = 1; });
